using System.Diagnostics;
using System.Runtime.InteropServices;
using System.Text;

namespace SharpCoder.Cli;

/// <summary>
/// Builds a short, bounded "environment context" block appended to the agent's system prompt via
/// <c>AgentOptions.CustomInstructions</c>. It tells the model what machine, workspace, toolchain and
/// tools it is actually running with, so it does not have to spend tool calls discovering them.
/// </summary>
/// <remarks>
/// Everything here is best-effort: a missing command, a non-git workspace or an unreadable directory
/// produces an "unavailable" line rather than failing startup. The block is deliberately bounded
/// (see the caps below) so it cannot eat a meaningful share of the context window.
/// </remarks>
internal sealed class EnvironmentDigest
{
    /// <summary>Maximum number of top-level workspace entries listed.</summary>
    internal const int MaxTopLevelEntries = 40;

    /// <summary>Maximum number of <c>git status --short</c> lines included.</summary>
    internal const int MaxGitStatusLines = 20;

    /// <summary>Maximum characters retained from any single command's output.</summary>
    internal const int MaxCommandOutputChars = 4_000;

    /// <summary>
    /// Placeholder for the resolved shell. <see cref="AgentFactory"/> substitutes it after the
    /// <c>CodingAgent</c> is constructed (which is when the shell is actually resolved).
    /// </summary>
    internal const string ShellPlaceholder = "{RESOLVED_SHELL}";

    /// <summary>Default timeout for a single probe command.</summary>
    private static readonly TimeSpan CommandTimeout = TimeSpan.FromSeconds(5);

    /// <summary>Runs a probe command and returns its (trimmed) stdout, or null when it cannot be run.</summary>
    /// <param name="fileName">Executable to run.</param>
    /// <param name="arguments">Space-separated arguments passed to the executable.</param>
    /// <param name="workingDirectory">Working directory for the probe.</param>
    /// <param name="ct">Cancellation token.</param>
    public delegate string? Probe(string fileName, string arguments, string workingDirectory, CancellationToken ct);

    private readonly Probe _probe;
    private readonly Func<DateTimeOffset> _now;

    /// <summary>Creates a digest builder. Production callers use <see cref="CreateDefault"/>.</summary>
    /// <param name="probe">Command runner used for <c>dotnet --version</c> and git probes.</param>
    /// <param name="now">Clock used for the timestamp (injectable for deterministic tests).</param>
    public EnvironmentDigest(Probe probe, Func<DateTimeOffset>? now = null)
    {
        _probe = probe ?? throw new ArgumentNullException(nameof(probe));
        _now = now ?? (() => DateTimeOffset.UtcNow);
    }

    /// <summary>Creates a digest builder that launches real probe processes with a short timeout.</summary>
    public static EnvironmentDigest CreateDefault() => new(RunProcess);

    /// <summary>
    /// Builds the environment block for a CLI run.
    /// </summary>
    /// <param name="options">Parsed CLI options (work directory, tool toggles, shell preference).</param>
    /// <param name="shellDescription">
    /// Human-readable shell description to embed. Production callers pass
    /// <see cref="ShellPlaceholder"/> and <c>AgentFactory</c> substitutes it with
    /// <c>CodingAgent.ResolvedBashShell</c> after construction.
    /// </param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>A multi-line markdown block. Never null or empty.</returns>
    public string Build(CliOptions options, string shellDescription, CancellationToken ct = default)
    {
        var workDirectory = options.WorkDirectory;
        var sb = new StringBuilder();

        sb.AppendLine("# Environment context (auto-generated by SharpCoder.Cli)");
        sb.AppendLine("Snapshot taken at startup. Re-check with a tool if state may have changed.");
        sb.AppendLine();

        // Runtime / OS — no external process needed.
        sb.AppendLine($"Date/time (UTC): {_now():yyyy-MM-dd HH:mm:ss}");
        sb.AppendLine($"OS: {DescribeOs()}");
        sb.AppendLine($".NET runtime: {Environment.Version}");
        sb.AppendLine($"Work directory: {workDirectory}");

        // Toolchain — one short probe.
        sb.AppendLine($"dotnet SDK: {ValueOrUnavailable(_probe("dotnet", "--version", workDirectory, ct))}");

        // Git state — three short probes; all degrade gracefully outside a repository.
        var branch = _probe("git", "rev-parse --abbrev-ref HEAD", workDirectory, ct);
        sb.AppendLine($"Git branch: {ValueOrUnavailable(branch)}");
        if (!string.IsNullOrWhiteSpace(branch))
        {
            AppendGitStatus(sb, _probe("git", "status --short", workDirectory, ct));
            sb.AppendLine($"Last commit: {ValueOrUnavailable(_probe("git", "log -1 --oneline", workDirectory, ct))}");
        }

        // Workspace shape — bounded, no recursion.
        sb.AppendLine("Top-level workspace entries:");
        AppendTopLevel(sb, workDirectory);

        // Capabilities — derived from the same options the agent is constructed with.
        sb.AppendLine();
        sb.AppendLine("Configured capabilities:");
        sb.AppendLine($"  Bash tool: {(options.EnableBash ? $"enabled (shell: {shellDescription})" : "disabled")}");
        sb.AppendLine($"  File tools: read_file, glob, grep{(options.ReadOnly ? string.Empty : ", write_file, edit_file")} ({(options.ReadOnly ? "read-only" : "writes enabled")})");
        sb.AppendLine("  Skills: enabled (list_skills, load_skill)");
        sb.AppendLine($"  Max steps: {options.MaxSteps}");

        return sb.ToString().TrimEnd();
    }

    private static string DescribeOs()
    {
        var platform = RuntimeInformation.IsOSPlatform(OSPlatform.Windows) ? "Windows"
            : RuntimeInformation.IsOSPlatform(OSPlatform.OSX) ? "macOS"
            : RuntimeInformation.IsOSPlatform(OSPlatform.Linux) ? "Linux"
            : "unknown";
        return $"{platform} ({RuntimeInformation.OSArchitecture}, {RuntimeInformation.ProcessArchitecture} process)";
    }

    private static string ValueOrUnavailable(string? value) =>
        string.IsNullOrWhiteSpace(value) ? "unavailable" : value!.Trim();

    private static void AppendGitStatus(StringBuilder sb, string? status)
    {
        if (status is null)
        {
            sb.AppendLine("Git status (short): unavailable");
            return;
        }

        sb.AppendLine("Git status (short):");
        var lines = status.Replace("\r\n", "\n").Split('\n').Where(l => l.Length > 0).ToList();
        if (lines.Count == 0)
        {
            sb.AppendLine("  (clean working tree)");
            return;
        }

        var kept = Math.Min(lines.Count, MaxGitStatusLines);
        for (var i = 0; i < kept; i++)
            sb.AppendLine($"  {lines[i]}");
        if (lines.Count > kept)
            sb.AppendLine($"  … ({lines.Count - kept} more entries)");
    }

    private static void AppendTopLevel(StringBuilder sb, string workDirectory)
    {
        try
        {
            var hidden = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
                { ".git", ".vs", "bin", "obj", "TestResults" };

            var entries = Directory.GetFileSystemEntries(workDirectory)
                .Select(Path.GetFileName)
                .Where(name => name is not null && !hidden.Contains(name))
                .Select(name => name!)
                .OrderBy(name => name, StringComparer.OrdinalIgnoreCase)
                .ToList();

            if (entries.Count == 0)
            {
                sb.AppendLine("  (empty)");
                return;
            }

            var kept = Math.Min(entries.Count, MaxTopLevelEntries);
            for (var i = 0; i < kept; i++)
            {
                var name = entries[i];
                var isDir = Directory.Exists(Path.Combine(workDirectory, name));
                sb.AppendLine($"  {name}{(isDir ? "/" : string.Empty)}");
            }

            if (entries.Count > kept)
                sb.AppendLine($"  … ({entries.Count - kept} more entries)");
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or ArgumentException)
        {
            sb.AppendLine("  (unavailable: workspace could not be listed)");
        }
    }

    private static string? RunProcess(string fileName, string arguments, string workingDirectory, CancellationToken ct)
    {
        Process? process = null;
        try
        {
            var psi = new ProcessStartInfo(fileName)
            {
                WorkingDirectory = workingDirectory,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true,
            };
            foreach (var arg in arguments.Split(' ', StringSplitOptions.RemoveEmptyEntries))
                psi.ArgumentList.Add(arg);

            process = Process.Start(psi);
            if (process is null) return null;

            // Drain both pipes asynchronously so a chatty stderr cannot deadlock the process.
            var stdout = process.StandardOutput.ReadToEndAsync(ct);
            var stderr = process.StandardError.ReadToEndAsync(ct);

            if (!process.WaitForExit((int)CommandTimeout.TotalMilliseconds))
            {
                TryKill(process);
                return null;
            }

            // The process has exited; the pipe reads finish promptly. Wait with a hard bound so a
            // stuck child can never hang CLI startup.
            var drains = Task.WhenAll(stdout, stderr);
            if (!drains.Wait(TimeSpan.FromSeconds(2), ct))
                return null;
            if (process.ExitCode != 0) return null;

            var text = stdout.Result;
            if (string.IsNullOrWhiteSpace(text)) return null;
            return text.Length > MaxCommandOutputChars ? text[..MaxCommandOutputChars] : text;
        }
        catch (Exception ex) when (ex is System.ComponentModel.Win32Exception
                                   or InvalidOperationException
                                   or IOException
                                   or OperationCanceledException
                                   or AggregateException
                                   or ArgumentException)
        {
            // Toolchain not installed, not a git repo, timed out, etc. — all best-effort.
            return null;
        }
        finally
        {
            process?.Dispose();
        }
    }

    private static void TryKill(Process process)
    {
        try { if (!process.HasExited) process.Kill(entireProcessTree: true); }
        catch (Exception ex) when (ex is InvalidOperationException or System.ComponentModel.Win32Exception or NotSupportedException)
        { /* best-effort cleanup */ }
    }
}
