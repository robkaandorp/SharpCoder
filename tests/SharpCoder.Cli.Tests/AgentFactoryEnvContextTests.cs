using Microsoft.Extensions.AI;

namespace SharpCoder.Cli.Tests;

public class AgentFactoryEnvContextTests
{
    [Fact]
    public async Task CreateAsync_EnvContextEnabled_AppendsDigestToCustomInstructions()
    {
        var fake = new FixedResponseClient();
        var digest = new EnvironmentDigest((_, _, _, _) => "PROBE-OUTPUT", () => DateTimeOffset.UnixEpoch);
        var options = CliOptions.Parse(new[] { "run", "task" })!;

        await using var factory = new AgentFactory(options, new ConsoleUi(), digest, _ => fake);
        var (agent, _) = await factory.CreateAsync();

        var prompt = await BuildSystemPromptAsync(agent, fake, TestContext.Current.CancellationToken);
        Assert.Contains("# Custom Instructions", prompt);
        Assert.Contains("# Environment context (auto-generated by SharpCoder.Cli)", prompt);
        Assert.Contains("PROBE-OUTPUT", prompt);
        Assert.Contains("dotnet SDK:", prompt);
        Assert.Contains("Bash tool: disabled", prompt);
        Assert.DoesNotContain(EnvironmentDigest.ShellPlaceholder, prompt);
    }

    [Fact]
    public async Task CreateAsync_NoEnvContext_LeavesCustomInstructionsEmpty()
    {
        var fake = new FixedResponseClient();
        var digest = new EnvironmentDigest((_, _, _, _) => "PROBE-OUTPUT", () => DateTimeOffset.UnixEpoch);
        var options = CliOptions.Parse(new[] { "run", "--no-env-context", "task" })!;

        await using var factory = new AgentFactory(options, new ConsoleUi(), digest, _ => fake);
        var (agent, _) = await factory.CreateAsync();

        var prompt = await BuildSystemPromptAsync(agent, fake, TestContext.Current.CancellationToken);
        Assert.DoesNotContain("# Custom Instructions", prompt);
        Assert.DoesNotContain("Environment context", prompt);
        Assert.DoesNotContain("PROBE-OUTPUT", prompt);
    }

    [Fact]
    public async Task CreateAsync_EnvContextEnabled_IncludesResolvedShellWhenBashEnabled()
    {
        var fake = new FixedResponseClient();
        var digest = new EnvironmentDigest((_, _, _, _) => null, () => DateTimeOffset.UnixEpoch);
        var options = CliOptions.Parse(new[] { "run", "--bash", "task" })!;

        await using var factory = new AgentFactory(options, new ConsoleUi(), digest, _ => fake);
        var (agent, _) = await factory.CreateAsync();

        var prompt = await BuildSystemPromptAsync(agent, fake, TestContext.Current.CancellationToken);
        Assert.Contains("Bash tool: enabled (shell:", prompt);
        Assert.DoesNotContain(EnvironmentDigest.ShellPlaceholder, prompt);
        Assert.Contains(agent.ResolvedBashShell!, prompt);
    }

    /// <summary>Executes one turn so CodingAgent.BuildSystemPrompt runs and the fake records the request.</summary>
    private static async Task<string> BuildSystemPromptAsync(CodingAgent agent, FixedResponseClient fake, CancellationToken ct)
    {
        var session = AgentSession.Create();
        await agent.ExecuteAsync(session, "hello", ct);
        var messages = fake.ReceivedMessages.Single();
        return messages[0].Text ?? string.Empty;
    }

    private sealed class FixedResponseClient : IChatClient
    {
        public List<IList<ChatMessage>> ReceivedMessages { get; } = [];

        public Task<ChatResponse> GetResponseAsync(
            IEnumerable<ChatMessage> messages,
            ChatOptions? options = null,
            CancellationToken cancellationToken = default)
        {
            ReceivedMessages.Add(messages.ToList());
            return Task.FromResult(new ChatResponse(new ChatMessage(ChatRole.Assistant, "Done.")));
        }

        public IAsyncEnumerable<ChatResponseUpdate> GetStreamingResponseAsync(
            IEnumerable<ChatMessage> messages,
            ChatOptions? options = null,
            CancellationToken cancellationToken = default)
            => throw new NotImplementedException();

        public object? GetService(Type serviceType, object? serviceKey = null) => null;
        public void Dispose() { }
    }
}
